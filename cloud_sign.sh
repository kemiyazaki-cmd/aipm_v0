# ================================================================
# メインルーティング
# ================================================================
main() {
  local command="${1:-help}"
  shift 2>/dev/null || true

  case "$command" in
    sign)    cmd_sign "$@" ;;
    verify)  cmd_verify "$@" ;;
    status)  cmd_status "$@" ;;
    list)    cmd_list "$@" ;;
    approve) cmd_approve "$@" ;;
    revoke)  cmd_revoke "$@" ;;
    log)     cmd_log "$@" ;;
    help|--help|-h) cmd_help ;;
    *)
      log_error "不明なコマンド: $command"
      cmd_help
      exit 1
      ;;
  esac
}

main "$@"
